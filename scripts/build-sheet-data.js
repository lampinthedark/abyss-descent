'use strict';
// Embeds the 0x72 DungeonTileset II (CC0) as a data URL so the survivor canvas
// can read its pixels on any host. A cross-origin redirect (raw.githack ->
// raw.githubusercontent) would otherwise taint the canvas and the sprites
// would fall back to circles. Run: node scripts/build-sheet-data.js
// Pass --check to fail when js/survivor-sheet.js is out of date.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const png = path.join(root, 'assets/0x72/dungeon-tileset-ii.png');
const out = path.join(root, 'js/survivor-sheet.js');

function render() {
  const b64 = fs.readFileSync(png).toString('base64');
  return '/* Generated by scripts/build-sheet-data.js from assets/0x72/dungeon-tileset-ii.png (0x72, CC0). Do not edit. */\n'
    + 'var SURVIVOR_SHEET_DATA = \'data:image/png;base64,' + b64 + '\';\n';
}

const text = render();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== text) {
    console.error('js/survivor-sheet.js is stale; run node scripts/build-sheet-data.js');
    process.exit(1);
  }
  console.log('sprite sheet data url in sync (' + text.length + ' bytes)');
} else {
  fs.writeFileSync(out, text);
  console.log('wrote js/survivor-sheet.js (' + text.length + ' bytes)');
}
